/**
 * Mutable handle for the current span.
 *
 * Prefer the ambient `evalSpan` export for most code so helpers deeper in the call
 * stack can annotate the active span without receiving an injected argument.
 */
export type TraceActiveSpan = {
  /** Rename the active span after it has been created. */
  setName(value: string): void;
  /** Set a single attribute on the active span. Later writes replace the same key. */
  setAttribute(key: string, value: unknown): void;
  /** Merge multiple attributes into the active span. */
  setAttributes(value: Record<string, unknown>): void;
};

/** Timestamp accepted by the external span lifecycle API. */
export type TraceSpanTimestamp = Date | string;

/** Info accepted by `evalTracer.startSpan(info)` for externally managed spans. */
export type TraceExternalSpanStartInfo = {
  /** Stable span id from the upstream tracer. Generated when omitted. */
  id?: string;
  /** Parent span id from the upstream tracer. Defaults to the active eval span. */
  parentId?: string | null;
  /** Semantic category used by the trace UI. */
  kind: string;
  /** Display name for the span. */
  name: string;
  /** Span start time. Defaults to now. */
  startedAt?: TraceSpanTimestamp;
  /** Initial span attributes. Later updates merge into this object. */
  attributes?: Record<string, unknown>;
};

/** Info accepted by `evalTracer.updateSpan(info)` for lifecycle updates. */
export type TraceExternalSpanUpdateInfo = {
  /** Span id previously passed to `evalTracer.startSpan(...)`. */
  id: string;
  /** Optional replacement display name. */
  name?: string;
  /** Attributes to merge into the recorded span. */
  attributes?: Record<string, unknown>;
  /** Optional status override, useful when the upstream tracer emits one. */
  status?: EvalTraceSpan['status'];
  /** Optional error payload to attach to the span. */
  error?: EvalTraceSpan['error'];
};

/** Info accepted by `evalTracer.endSpan(info)` for externally managed spans. */
export type TraceExternalSpanEndInfo = TraceExternalSpanUpdateInfo & {
  /** Span end time. Defaults to now. */
  endedAt?: TraceSpanTimestamp;
};

/** Info accepted by `evalTracer.recordSpan(info)` for completed external spans. */
export type TraceExternalSpanRecordInfo = {
  /** Stable span id from the upstream tracer. Generated when omitted. */
  id?: string;
  /** Parent span id from the upstream tracer. Defaults to the active eval span. */
  parentId?: string | null;
  /** Semantic category used by the trace UI. */
  kind: string;
  /** Display name for the span. */
  name: string;
  /** Span start time. Defaults to now. */
  startedAt?: TraceSpanTimestamp;
  /** Span end time. Defaults to the start time. */
  endedAt?: TraceSpanTimestamp | null;
  /** Final span status. Defaults to `ok`. */
  status?: EvalTraceSpan['status'];
  /** Final span attributes. */
  attributes?: Record<string, unknown>;
  /** Optional error payload to attach to the span. */
  error?: EvalTraceSpan['error'];
};

/** Mutable handle returned by `evalTracer.startSpan(...)`. */
export type TraceExternalSpanHandle = TraceActiveSpan & {
  /** Recorded span id, either caller-provided or generated by the SDK. */
  id: string;
  /** Finish the external span and merge any final fields. */
  end(info?: Omit<TraceExternalSpanEndInfo, 'id'>): void;
};

let spanIdCounter = 0;
const errorCoreFields = new Set(['name', 'message', 'stack', 'capturedAt']);

function generateSpanId(): string {
  spanIdCounter++;
  return `span_${String(Date.now())}_${String(spanIdCounter)}`;
}

function isRecord(value: unknown): value is Record<string, unknown> {
  return typeof value === 'object' && value !== null && !Array.isArray(value);
}

function formatUnknownErrorMessage(error: unknown): string {
  if (typeof error === 'string') return error;
  if (typeof error === 'number' || typeof error === 'boolean') {
    return String(error);
  }
  if (typeof error === 'bigint') return String(error);
  if (typeof error === 'symbol') return error.description ?? 'Symbol';
  if (typeof error === 'function') {
    return error.name ? `[function ${error.name}]` : '[function]';
  }
  if (error === undefined) return 'undefined';
  if (error === null) return 'null';

  try {
    return JSON.stringify(error);
  } catch {
    return 'Unknown error';
  }
}

function getErrorExtraFields(error: object): Record<string, unknown> {
  return Object.fromEntries(
    Object.entries(error).filter(([key]) => !errorCoreFields.has(key)),
  );
}

function updateCurrentSpan(update: (currentSpan: EvalTraceSpan) => void): void {
  const scope = getCurrentScope();
  const currentSpan = scope?.activeSpanStack.at(-1);
  if (!currentSpan) return;
  update(currentSpan);
}

function noopActiveSpan(): TraceActiveSpan {
  return { setName() {}, setAttribute() {}, setAttributes() {} };
}

function noopExternalSpan(id: string): TraceExternalSpanHandle {
  return { id, setName() {}, setAttribute() {}, setAttributes() {}, end() {} };
}

function mergeSpanAttributes(
  span: EvalTraceSpan,
  attributes: Record<string, unknown>,
): void {
  span.attributes = { ...span.attributes, ...attributes };
}

function normalizeTraceError(
  error: unknown,
  capturedAt: string | undefined = undefined,
): EvalTraceSpanError {
  if (error instanceof Error) {
    const extraFields = getErrorExtraFields(error);
    return {
      ...extraFields,
      name: error.name,
      message: error.message,
      stack: error.stack,
      capturedAt,
    };
  }

  if (isRecord(error)) {
    const extraFields = getErrorExtraFields(error);
    const name = typeof error.name === 'string' ? error.name : undefined;
    const stack = typeof error.stack === 'string' ? error.stack : undefined;
    const message =
      error.message === undefined
        ? formatUnknownErrorMessage(error)
        : formatUnknownErrorMessage(error.message);

    return {
      ...extraFields,
      ...(name === undefined ? {} : { name }),
      message,
      ...(stack === undefined ? {} : { stack }),
      capturedAt,
    };
  }

  return { message: String(error), capturedAt };
}

function normalizeTraceErrors(
  errorOrErrors: unknown,
  additionalErrors: readonly unknown[],
  capturedAt: string,
): EvalTraceSpanError[] {
  const rawErrors =
    additionalErrors.length > 0
      ? [errorOrErrors, ...additionalErrors]
      : Array.isArray(errorOrErrors)
        ? errorOrErrors
        : [errorOrErrors];
  return rawErrors.map((error) => normalizeTraceError(error, capturedAt));
}

function appendSpanErrors(
  span: EvalTraceSpan,
  errors: readonly EvalTraceSpanError[],
): void {
  if (errors.length === 0) return;
  const latestError = errors.at(-1);
  if (latestError === undefined) return;
  span.errors = [...(span.errors ?? []), ...errors];
  span.error = latestError;
  span.status = 'error';
}

function hasSpanError(span: EvalTraceSpan): boolean {
  return span.error !== undefined || (span.errors?.length ?? 0) > 0;
}

function finishSpanWithoutThrownError(span: EvalTraceSpan): void {
  span.status = hasSpanError(span) ? 'error' : 'ok';
  span.endedAt = new Date().toISOString();
}

function createSpanHandle(span: EvalTraceSpan): TraceActiveSpan {
  return {
    setName(value) {
      span.name = value;
    },
    setAttribute(key, value) {
      mergeSpanAttributes(span, { [key]: value });
    },
    setAttributes(value) {
      mergeSpanAttributes(span, value);
    },
  };
}

function createExternalSpanHandle(id: string): TraceExternalSpanHandle {
  return {
    id,
    setName(value) {
      updateExternalSpan({ id, name: value });
    },
    setAttribute(key, value) {
      updateExternalSpan({ id, attributes: { [key]: value } });
    },
    setAttributes(value) {
      updateExternalSpan({ id, attributes: value });
    },
    end(info = {}) {
      endExternalSpan({ ...info, id });
    },
  };
}

function toIsoTimestamp(value: TraceSpanTimestamp | undefined): string {
  if (value === undefined) return new Date().toISOString();
  if (typeof value === 'string') return value;
  return value.toISOString();
}

function findSpan(scope: EvalCaseScope, id: string): EvalTraceSpan | undefined {
  return scope.spans.find((span) => span.id === id);
}

function resolveExternalParentId(
  scope: EvalCaseScope,
  parentId: string | null | undefined,
): string | null {
  if (parentId !== undefined) return parentId;
  return scope.activeSpanStack.at(-1)?.id ?? null;
}

function startExternalSpan(
  info: TraceExternalSpanStartInfo,
): TraceExternalSpanHandle {
  const id = info.id ?? generateSpanId();
  const scope = getCurrentScope();
  if (!scope) return noopExternalSpan(id);

  const existing = findSpan(scope, id);
  if (existing) {
    existing.parentId = resolveExternalParentId(scope, info.parentId);
    existing.kind = info.kind;
    existing.name = info.name;
    existing.startedAt = toIsoTimestamp(info.startedAt);
    existing.status = 'running';
    existing.endedAt = null;
    if (info.attributes !== undefined) {
      existing.attributes = info.attributes;
    }
    return createExternalSpanHandle(id);
  }

  scope.spans.push({
    id,
    parentId: resolveExternalParentId(scope, info.parentId),
    caseId: scope.caseId,
    kind: info.kind,
    name: info.name,
    startedAt: toIsoTimestamp(info.startedAt),
    endedAt: null,
    status: 'running',
    attributes: info.attributes,
  });

  return createExternalSpanHandle(id);
}

function updateExternalSpan(info: TraceExternalSpanUpdateInfo): void {
  const scope = getCurrentScope();
  if (!scope) return;
  const span = findSpan(scope, info.id);
  if (!span) return;
  if (info.name !== undefined) span.name = info.name;
  if (info.status !== undefined) span.status = info.status;
  if (info.error !== undefined) span.error = info.error;
  if (info.attributes !== undefined) {
    mergeSpanAttributes(span, info.attributes);
  }
}

function endExternalSpan(info: TraceExternalSpanEndInfo): void {
  const scope = getCurrentScope();
  if (!scope) return;
  const span = findSpan(scope, info.id);
  if (!span) return;

  updateExternalSpan(info);
  span.status = info.status ?? (info.error ? 'error' : 'ok');
  span.endedAt = toIsoTimestamp(info.endedAt);
}

function recordExternalSpan(info: TraceExternalSpanRecordInfo): string {
  const id = info.id ?? generateSpanId();
  const scope = getCurrentScope();
  if (!scope) return id;

  const startedAt = toIsoTimestamp(info.startedAt);
  const endedAt =
    info.endedAt === null
      ? null
      : info.endedAt
        ? toIsoTimestamp(info.endedAt)
        : startedAt;
  const existing = findSpan(scope, id);
  const status = info.status ?? (info.error ? 'error' : 'ok');

  if (existing) {
    existing.parentId = resolveExternalParentId(scope, info.parentId);
    existing.kind = info.kind;
    existing.name = info.name;
    existing.startedAt = startedAt;
    existing.endedAt = endedAt;
    existing.status = status;
    existing.attributes = info.attributes;
    existing.error = info.error;
    return id;
  }

  scope.spans.push({
    id,
    parentId: resolveExternalParentId(scope, info.parentId),
    caseId: scope.caseId,
    kind: info.kind,
    name: info.name,
    startedAt,
    endedAt,
    status,
    attributes: info.attributes,
    error: info.error,
  });

  return id;
}

/**
 * Ambient handle for the active span in the current async context.
 *
 * Calls are no-ops when executed outside of `evalTracer.span(...)`.
 */
export const evalSpan: TraceActiveSpan = {
  setName(value) {
    updateCurrentSpan((currentSpan) => {
      currentSpan.name = value;
    });
  },
  setAttribute(key, value) {
    updateCurrentSpan((currentSpan) => {
      mergeSpanAttributes(currentSpan, { [key]: value });
    });
  },
  setAttributes(value) {
    updateCurrentSpan((currentSpan) => {
      mergeSpanAttributes(currentSpan, value);
    });
  },
};

/**
 * Attach one or more recoverable errors to the active eval span.
 *
 * The active span is marked as `error` even if its callback later completes
 * without throwing. Calls outside `evalTracer.span(...)` are ignored.
 */
export function captureEvalSpanError(
  errorOrErrors: unknown,
  ...additionalErrors: readonly unknown[]
): void {
  const errors = normalizeTraceErrors(
    errorOrErrors,
    additionalErrors,
    new Date().toISOString(),
  );
  updateCurrentSpan((currentSpan) => {
    appendSpanErrors(currentSpan, errors);
  });
}

type TraceSpanInfoBase = {
  kind: string;
  name: string;
  attributes?: Record<string, unknown>;
};

/** Info accepted by `evalTracer.span(info, fn)` when creating an uncached span. */
export type TraceSpanInfoUncached = TraceSpanInfoBase & { cache?: undefined };

/**
 * Info accepted by `evalTracer.span(info, fn)` when opting in to caching.
 *
 * Cached spans return `Promise<unknown>` because the replayed value comes from
 * a JSON round-trip on cache hit. Narrow the value yourself when you need a
 * typed return.
 */
export type TraceSpanInfoCached = TraceSpanInfoBase & {
  cache: SpanCacheOptions;
};

/** Info accepted by `evalTracer.span(info, fn)`. */
export type TraceSpanInfo = TraceSpanInfoUncached | TraceSpanInfoCached;

function traceSpan<T>(
  info: TraceSpanInfoUncached,
  fn: () => Promise<T> | T,
): Promise<T>;
function traceSpan<T>(
  info: TraceSpanInfoUncached,
  fn: (span: TraceActiveSpan) => Promise<T> | T,
): Promise<T>;
function traceSpan(
  info: TraceSpanInfoCached,
  fn: () => unknown,
): Promise<unknown>;
function traceSpan(
  info: TraceSpanInfoCached,
  fn: (span: TraceActiveSpan) => unknown,
): Promise<unknown>;
async function traceSpan(
  info: TraceSpanInfo,
  fn: (span: TraceActiveSpan) => unknown,
): Promise<unknown> {
  const scope = getCurrentScope();
  if (!scope) {
    return await fn(noopActiveSpan());
  }

  const id = generateSpanId();
  const parentId = scope.activeSpanStack.at(-1)?.id ?? null;

  const spanRecord: EvalTraceSpan = {
    id,
    parentId,
    caseId: scope.caseId,
    kind: info.kind,
    name: info.name,
    startedAt: new Date().toISOString(),
    endedAt: null,
    status: 'running',
    attributes: info.attributes,
  };

  scope.spans.push(spanRecord);
  scope.spanStack.push(id);
  scope.activeSpanStack.push(spanRecord);

  const activeSpan = createSpanHandle(spanRecord);

  try {
    const cacheOpts = info.cache;
    const cacheCtx = scope.cacheContext;
    if (
      cacheOpts !== undefined &&
      cacheCtx !== undefined &&
      scope.replayingDepth === 0
    ) {
      const ctx = cacheCtx;
      const namespace = cacheOpts.namespace ?? `${ctx.evalId}__${info.name}`;
      const keyHash = await hashCacheKey({
        namespace,
        codeFingerprint: ctx.codeFingerprint,
        key: cacheOpts.key,
      });

      mergeSpanAttributes(spanRecord, {
        'cache.key': keyHash,
        'cache.namespace': namespace,
      });

      if (ctx.mode === 'use') {
        const hit = await ctx.adapter.lookup(namespace, keyHash);
        if (hit) {
          const storedAt = hit.storedAt;
          const age = Date.now() - new Date(storedAt).getTime();
          mergeSpanAttributes(spanRecord, {
            'cache.status': 'hit',
            'cache.storedAt': storedAt,
            'cache.age': age,
          });
          replayRecording(scope, spanRecord, hit.recording);
          spanRecord.status =
            hit.recording.finalStatus ??
            (hasSpanError(spanRecord) ? 'error' : 'ok');
          spanRecord.endedAt = new Date().toISOString();
          return hit.recording.returnValue;
        }
        mergeSpanAttributes(spanRecord, { 'cache.status': 'miss' });
      } else if (ctx.mode === 'refresh') {
        mergeSpanAttributes(spanRecord, { 'cache.status': 'refresh' });
      } else {
        mergeSpanAttributes(spanRecord, { 'cache.status': 'bypass' });
      }

      const frame: CacheRecordingFrame = {
        baseSpanIndex: scope.spans.length,
        cachedSpanId: id,
        ops: [],
      };
      scope.recordingStack.push(frame);

      let bodyResult: unknown;
      try {
        bodyResult = await fn(activeSpan);
      } finally {
        scope.recordingStack.pop();
      }

      appendSubSpanOps(scope, frame);
      finishSpanWithoutThrownError(spanRecord);

      if (ctx.mode !== 'bypass') {
        const returnValue = toJsonSafe(bodyResult);
        const recording: CacheRecording = {
          returnValue,
          finalAttributes: stripCacheAttributes(spanRecord.attributes),
          finalStatus: spanRecord.status,
          finalError: spanRecord.error,
          finalErrors: spanRecord.errors,
          ops: frame.ops,
        };
        const entry: CacheEntry = {
          version: 1,
          key: keyHash,
          namespace,
          spanName: info.name,
          spanKind: info.kind,
          storedAt: new Date().toISOString(),
          codeFingerprint: ctx.codeFingerprint,
          recording,
        };
        await ctx.adapter.write(entry);
      }

      return bodyResult;
    }

    const result = await fn(activeSpan);
    finishSpanWithoutThrownError(spanRecord);
    return result;
  } catch (error) {
    spanRecord.status = 'error';
    spanRecord.endedAt = new Date().toISOString();
    spanRecord.error = normalizeTraceError(error);
    throw error;
  } finally {
    scope.spanStack.pop();
    scope.activeSpanStack.pop();
  }
}

/**
 * Trace builder used to create hierarchical spans and checkpoints during eval
 * execution.
 */
export const evalTracer = {
  /** Run a callback inside a new trace span and record its lifecycle. */
  span: traceSpan,

  /**
   * Start a span whose lifecycle is controlled by an external tracer/exporter.
   *
   * Calls are no-ops outside an eval case scope, except that a generated or
   * caller-provided id is still returned for ergonomic adapter code.
   */
  startSpan: startExternalSpan,

  /**
   * Merge updates into an externally managed span that was started earlier.
   *
   * This is intended for observability exporters that receive span update
   * events before the final end event.
   */
  updateSpan: updateExternalSpan,

  /**
   * Finish an externally managed span and attach final attributes or errors.
   *
   * Missing spans are ignored so exporter adapters can safely forward events
   * even when they are emitted outside an eval case scope.
   */
  endSpan: endExternalSpan,

  /**
   * Record a complete external span in one call.
   *
   * Use this when an upstream tracer only exposes completed spans rather than
   * start/update/end events.
   */
  recordSpan: recordExternalSpan,

  /** Record a named point-in-time value alongside the trace. */
  checkpoint(name: string, data: unknown): void {
    const scope = getCurrentScope();
    if (!scope) return;
    scope.checkpoints.set(name, data);
    const id = generateSpanId();
    const parentId = scope.spanStack.at(-1) ?? null;
    scope.spans.push({
      id,
      parentId,
      caseId: scope.caseId,
      kind: 'checkpoint',
      name,
      startedAt: new Date().toISOString(),
      endedAt: new Date().toISOString(),
      status: 'ok',
      attributes: { value: data },
    });
    if (scope.replayingDepth === 0) {
      const top = scope.recordingStack.at(-1);
      if (top) top.ops.push({ kind: 'checkpoint', name, data });
    }
  },
};

/** Build a queryable trace tree helper from a flat span list and checkpoints. */
export function buildTraceTree(
  spans: EvalTraceSpan[],
  checkpoints: Map<string, unknown>,
): EvalTraceTree {
  const rootSpans = spans.filter((s) => s.parentId === null);

  return {
    spans,
    rootSpans,
    findSpan(name) {
      return spans.find((s) => s.name === name);
    },
    findSpansByKind(kind) {
      return spans.filter((s) => s.kind === kind);
    },
    flattenDfs() {
      const result: EvalTraceSpan[] = [];
      function visit(parentId: string | null) {
        for (const childSpan of spans) {
          if (childSpan.parentId === parentId) {
            result.push(childSpan);
            visit(childSpan.id);
          }
        }
      }
      visit(null);
      return result;
    },
    checkpoints,
  };
}

type CacheKeyHashInput = {
  namespace: string;
  codeFingerprint: string;
  key: unknown;
};

class SerializedCacheKeyValue {
  readonly value: string;

  constructor(value: string) {
    this.value = value;
  }
}

/**
 * Hash the components of a cache key into a deterministic hex digest.
 *
 * Native `Blob` and `File` values are read asynchronously and hashed by
 * content. Use `hashCacheKeySync` only when the key contains no async values.
 */
export async function hashCacheKey(input: CacheKeyHashInput): Promise<string> {
  const materialized = await materializeAsyncCacheKeyValue(input);
  return hashCacheKeySyncMaterialized(materialized);
}

/**
 * Synchronously hash cache key components. This supports JSON-like data and
 * in-memory binary values such as `Buffer`, `ArrayBuffer`, and typed arrays,
 * but cannot content-hash native `Blob` or `File` values.
 */
export function hashCacheKeySync(input: CacheKeyHashInput): string {
  return hashCacheKeySyncMaterialized(input);
}

function hashCacheKeySyncMaterialized(input: unknown): string {
  return createHash('sha256')
    .update(getCompositeKey(input, { stringify: stringifyCacheKeyValue }))
    .digest('hex');
}

function stringifyCacheKeyValue(value: unknown): string | undefined {
  if (value instanceof SerializedCacheKeyValue) {
    return value.value;
  }
  if (Buffer.isBuffer(value)) {
    return `$buffer:${hashBytes(value)}`;
  }
  if (isArrayBuffer(value)) {
    return `$arrayBuffer:${hashBytes(new Uint8Array(value))}`;
  }
  if (isSharedArrayBuffer(value)) {
    return `$sharedArrayBuffer:${hashBytes(new Uint8Array(value))}`;
  }
  if (isArrayBufferView(value)) {
    const bytes = new Uint8Array(
      value.buffer,
      value.byteOffset,
      value.byteLength,
    );
    return `$${value.constructor.name}:${hashBytes(bytes)}`;
  }
  if (isFile(value)) {
    return `$file:${getCompositeKey({
      lastModified: value.lastModified,
      name: value.name,
      size: value.size,
      type: value.type,
    })}`;
  }
  if (isBlob(value)) {
    return `$blob:${getCompositeKey({ size: value.size, type: value.type })}`;
  }
  return undefined;
}

async function materializeAsyncCacheKeyValue(
  value: unknown,
  refs = new WeakSet<object>(),
): Promise<unknown> {
  const serialized = await stringifyAsyncCacheKeyValue(value);
  if (serialized !== undefined) {
    return new SerializedCacheKeyValue(serialized);
  }
  if (stringifyCacheKeyValue(value) !== undefined) return value;
  if (!value || typeof value !== 'object') return value;
  if (Array.isArray(value)) {
    const items: unknown[] = [];
    for (const item of value) {
      items.push(await materializeAsyncCacheKeyValue(item, refs));
    }
    return items;
  }

  if (refs.has(value)) throw new Error('Circular reference detected');
  refs.add(value);
  const entries: [string, unknown][] = [];
  for (const [key, entryValue] of Object.entries(value)) {
    entries.push([key, await materializeAsyncCacheKeyValue(entryValue, refs)]);
  }
  refs.delete(value);
  return Object.fromEntries(entries);
}

async function stringifyAsyncCacheKeyValue(
  value: unknown,
): Promise<string | undefined> {
  if (isFile(value)) {
    return `$file:${getCompositeKey({
      bytes: await hashBlobBytes(value),
      lastModified: value.lastModified,
      name: value.name,
      size: value.size,
      type: value.type,
    })}`;
  }
  if (isBlob(value)) {
    return `$blob:${getCompositeKey({
      bytes: await hashBlobBytes(value),
      size: value.size,
      type: value.type,
    })}`;
  }
  return undefined;
}

async function hashBlobBytes(value: Blob): Promise<string> {
  return hashBytes(new Uint8Array(await value.arrayBuffer()));
}

function hashBytes(value: NodeJS.ArrayBufferView): string {
  return createHash('sha256').update(value).digest('hex');
}

function isArrayBuffer(value: unknown): value is ArrayBuffer {
  return value instanceof ArrayBuffer;
}

function isSharedArrayBuffer(value: unknown): value is SharedArrayBuffer {
  return value instanceof SharedArrayBuffer;
}

function isArrayBufferView(value: unknown): value is ArrayBufferView {
  return ArrayBuffer.isView(value);
}

function isBlob(value: unknown): value is Blob {
  return value instanceof Blob;
}

function isFile(value: unknown): value is File {
  return value instanceof File;
}

function toJsonSafe(value: unknown): unknown {
  if (value === undefined) return undefined;
  const text = JSON.stringify(value);
  const parsed: unknown = JSON.parse(text);
  return parsed;
}

function stripCacheAttributes(
  attributes: Record<string, unknown> | undefined,
): Record<string, unknown> {
  if (!attributes) return {};
  const result: Record<string, unknown> = {};
  for (const [key, value] of Object.entries(attributes)) {
    if (!key.startsWith('cache.')) {
      result[key] = value;
    }
  }
  return result;
}

function serializeSubSpanTree(
  scope: EvalCaseScope,
  spanId: string,
): SerializedCacheSpan {
  const original = scope.spans.find((s) => s.id === spanId);
  if (!original) {
    return {
      kind: 'custom',
      name: 'unknown',
      attributes: undefined,
      status: 'ok',
      error: undefined,
      errors: undefined,
      children: [],
    };
  }
  const children = scope.spans
    .filter((s) => s.parentId === spanId)
    .map((child) => serializeSubSpanTree(scope, child.id));
  return {
    kind: original.kind,
    name: original.name,
    attributes: original.attributes,
    status: original.status,
    error: original.error,
    errors: original.errors,
    children,
  };
}

function appendSubSpanOps(
  scope: EvalCaseScope,
  frame: CacheRecordingFrame,
): void {
  for (let i = frame.baseSpanIndex; i < scope.spans.length; i++) {
    const candidate = scope.spans[i];
    if (candidate?.parentId === frame.cachedSpanId) {
      frame.ops.push({
        kind: 'subSpan',
        span: serializeSubSpanTree(scope, candidate.id),
      });
    }
  }
}

function replayRecording(
  scope: EvalCaseScope,
  parentSpan: EvalTraceSpan,
  recording: CacheRecording,
): void {
  scope.replayingDepth++;
  try {
    for (const op of recording.ops) {
      applyRecordingOp(scope, parentSpan, op);
    }
    if (Object.keys(recording.finalAttributes).length > 0) {
      mergeSpanAttributes(parentSpan, recording.finalAttributes);
    }
    if (recording.finalError !== undefined) {
      parentSpan.error = recording.finalError;
    }
    if (recording.finalErrors !== undefined) {
      parentSpan.errors = recording.finalErrors;
    }
  } finally {
    scope.replayingDepth--;
  }
}

function applyRecordingOp(
  scope: EvalCaseScope,
  parentSpan: EvalTraceSpan,
  op: CacheRecordingOp,
): void {
  if (op.kind === 'setOutput') {
    scope.outputs[op.key] = op.value;
    return;
  }
  if (op.kind === 'incrementOutput') {
    const existing = scope.outputs[op.key];
    if (existing === undefined) {
      scope.outputs[op.key] = op.delta;
    } else if (typeof existing === 'number') {
      scope.outputs[op.key] = existing + op.delta;
    } else {
      scope.assertionFailures.push({
        message: `replay incrementEvalOutput("${op.key}"): existing value is ${typeof existing}, expected number`,
      });
    }
    return;
  }
  if (op.kind === 'checkpoint') {
    scope.checkpoints.set(op.name, op.data);
    return;
  }
  replaySerializedSpan(scope, parentSpan.id, op.span);
}

function replaySerializedSpan(
  scope: EvalCaseScope,
  parentId: string | null,
  serialized: SerializedCacheSpan,
): void {
  const id = generateSpanId();
  const now = new Date().toISOString();
  const replayed: EvalTraceSpan = {
    id,
    parentId,
    caseId: scope.caseId,
    kind: serialized.kind,
    name: serialized.name,
    startedAt: now,
    endedAt: now,
    status: serialized.status,
    attributes: serialized.attributes,
    error: serialized.error,
    errors: serialized.errors,
  };
  scope.spans.push(replayed);
  for (const child of serialized.children) {
    replaySerializedSpan(scope, id, child);
  }
}
